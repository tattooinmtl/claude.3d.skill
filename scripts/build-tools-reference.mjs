#!/usr/bin/env node
/**
 * build-tools-reference.mjs
 *
 * Writes references/tools.md from the server's own tool list.
 *
 * The reference is generated rather than written by hand, for two reasons.
 * A hand-written list drifts the moment the server changes, and a drifted
 * list is worse than none - the agent trusts it. And the tool descriptions
 * the server ships carry the real credit cost of each call, which is exactly
 * the information an agent needs before it spends someone's money.
 *
 * Usage: node scripts/build-tools-reference.mjs
 */

import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pluginRoot = join(here, '..');

const child = spawn('node', [join(pluginRoot, 'mcp', 'serve.mjs')], {
  stdio: ['pipe', 'pipe', 'inherit'],
});

const pending = new Map();
let nextId = 1;
let buffer = '';

child.stdout.setEncoding('utf8');
child.stdout.on('data', (chunk) => {
  buffer += chunk;
  let i;
  while ((i = buffer.indexOf('\n')) >= 0) {
    const line = buffer.slice(0, i).trim();
    buffer = buffer.slice(i + 1);
    if (!line) continue;
    let msg;
    try { msg = JSON.parse(line); } catch { continue; }
    if (msg.id !== undefined && pending.has(msg.id)) {
      pending.get(msg.id)(msg);
      pending.delete(msg.id);
    }
  }
});

const request = (method, params) =>
  new Promise((resolve) => {
    const id = nextId++;
    const timer = setTimeout(() => resolve({ id, error: { message: 'timeout' } }), 60000);
    pending.set(id, (m) => { clearTimeout(timer); resolve(m); });
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n');
  });

const init = await request('initialize', {
  protocolVersion: '2024-11-05',
  capabilities: {},
  clientInfo: { name: 'build-tools-reference', version: '0.1.0' },
});
child.stdin.write(
  JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized', params: {} }) + '\n',
);

const list = await request('tools/list', {});
const tools = list?.result?.tools ?? [];
if (!tools.length) {
  console.error('the server published no tools - is it running?');
  process.exit(1);
}

const server = init?.result?.serverInfo ?? {};

/**
 * Pull the credit cost out of the server's own description.
 *
 * The cost turns up in two shapes. Some tools put it on its own line
 * ("...minutes.\nCost: 20 credits ..."). Others put it inside the first
 * sentence ("Texture a SUCCEEDED preview. Cost: 10 credits (15 at 8K). Get
 * the user's approval first..."). Both have to be caught.
 *
 * A period only ends the cost when whitespace or the end of the line follows
 * it, so "meshy-7.1" and "meshy-t2.5" do not cut the string in half. A plain
 * sentence match turns "20 credits (meshy-7.1 / latest / meshy-6)" into
 * "20 credits (meshy-7" - which on a price list is not a rounding error.
 */
function costOf(text) {
  const withStop = text.match(/Cost:\s*([^\n]*?)\.(?=\s|$)/);
  if (withStop) return withStop[1].trim();
  const toLineEnd = text.match(/Cost:\s*([^\n]+)/);
  if (toLineEnd) return toLineEnd[1].trim();
  if (/\bFREE\b/.test(text) || /(^|\s)Free\./.test(text)) return 'free';
  return '';
}

const lines = [];
lines.push('<!--');
lines.push('  Generated by scripts/build-tools-reference.mjs - do not edit by hand.');
lines.push(`  Source: ${server.name} ${server.version}, ${tools.length} tools.`);
lines.push('-->');
lines.push('');
lines.push('# The Meshy MCP tool surface');
lines.push('');
lines.push(
  `The \`meshy\` MCP server publishes **${tools.length} tools**. This is the whole`,
  'list, with the parameters each one actually takes and the credit cost the',
  'server itself states.',
);
lines.push('');
lines.push(
  'The costs are taken from the tool descriptions rather than from a price list,',
  'so they match what the server will actually charge. A call that is not marked',
  'free is not free - check the balance before it.',
);
lines.push('');
lines.push('## Contents');
lines.push('');
for (const t of tools) {
  const cost = costOf(t.description ?? '');
  lines.push(`- [\`${t.name}\`](#${t.name.replace(/_/g, '')}) ${cost ? `- ${cost}` : ''}`.trimEnd());
}
lines.push('');

for (const t of tools) {
  const description = (t.description ?? '').trim();
  const cost = costOf(description);
  lines.push(`## ${t.name}`);
  lines.push('');
  if (description) {
    // The description is the server's own prose, multi-line. It already
    // carries its own Cost: line, so it is not repeated underneath.
    for (const para of description.split(/\n{2,}/)) {
      lines.push(para.trim());
      lines.push('');
    }
  } else {
    lines.push('*(no description)*');
    lines.push('');
  }

  const props = t.inputSchema?.properties ?? {};
  const required = new Set(t.inputSchema?.required ?? []);
  const names = Object.keys(props);

  if (names.length) {
    lines.push('**Parameters**');
    lines.push('');
    for (const name of names) {
      const p = props[name] ?? {};
      const type = p.type ?? (p.enum ? 'enum' : p.anyOf ? 'anyOf' : '?');
      const flags = [];
      if (required.has(name)) flags.push('required');
      if (p.enum) flags.push(`one of ${p.enum.join(' | ')}`);
      if (p.default !== undefined) flags.push(`default ${JSON.stringify(p.default)}`);
      const desc = (p.description ?? '').replace(/\s+/g, ' ').trim();
      lines.push(`- \`${name}\`${flags.length ? ` (${flags.join(', ')})` : ''} - ${type}${desc ? `: ${desc}` : ''}`);
    }
    lines.push('');
  } else {
    lines.push('**Parameters:** none.');
    lines.push('');
  }

  if (t.outputSchema) {
    lines.push('Returns a structured result (the server declares an output schema).');
    lines.push('');
  }
}

const out = join(pluginRoot, 'references', 'tools.md');
writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`wrote ${out} (${tools.length} tools)`);
child.stdin.end();
process.exit(0);
